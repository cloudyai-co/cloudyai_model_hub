#!/usr/bin/env python3
"""Write ``frontend/css/fonts.css`` from the WOFF2 files in ``frontend/fonts``.

Each ``@font-face`` rule gets a ``unicode-range`` taken from the file's character map, so browsers only
download the subset a page needs. Run this after ``scripts/build_fonts.py`` (or after replacing a font).

    python scripts/gen_font_css.py
"""

from __future__ import annotations

import sys
from collections import defaultdict
from pathlib import Path

from fontTools.ttLib import TTFont

REPO_ROOT = Path(__file__).resolve().parent.parent
FONT_DIR = REPO_ROOT / "frontend" / "fonts"
OUTPUT = REPO_ROOT / "frontend" / "css" / "fonts.css"

FAMILY_NAMES = {"IBMPlexSans": "Plex Sans", "IBMPlexSerif": "Plex Serif", "IBMPlexMono": "Plex Mono"}
WEIGHTS = {"Regular": 400, "Medium": 500, "SemiBold": 600, "Italic": 400}
SUBSET_ORDER = {"Latin1": 0, "Latin2": 1}


def unicode_ranges(codepoints: list[int]) -> str:
    """Compress sorted code points into a CSS ``unicode-range`` list."""
    parts: list[str] = []
    start = prev = None
    for cp in codepoints:
        if start is None:
            start = prev = cp
        elif cp == prev + 1:
            prev = cp
        else:
            parts.append((start, prev))
            start = prev = cp
    if start is not None:
        parts.append((start, prev))
    rendered = []
    for first, last in parts:
        rendered.append(f"U+{first:04X}" if first == last else f"U+{first:04X}-{last:04X}")
    return ", ".join(rendered)


def parse_name(path: Path) -> tuple[str, str, str]:
    family, style, subset = path.stem.split("-")
    return family, style, subset


def build_css() -> str:
    faces: dict[str, list[tuple[int, str, str]]] = defaultdict(list)
    rules: list[str] = []
    for path in sorted(FONT_DIR.glob("*.woff2")):
        family, style, subset = parse_name(path)
        if family not in FAMILY_NAMES or style not in WEIGHTS:
            raise SystemExit(f"Unexpected font file name: {path.name}")
        cmap = TTFont(path).getBestCmap() or {}
        span = unicode_ranges(sorted(cmap))
        italic = style == "Italic"
        weight = WEIGHTS[style]
        rules.append(
            "\n".join(
                [
                    "@font-face {",
                    f'  font-family: "{FAMILY_NAMES[family]}";',
                    f"  font-style: {'italic' if italic else 'normal'};",
                    f"  font-weight: {weight};",
                    "  font-display: swap;",
                    f'  src: url("../fonts/{path.name}") format("woff2");',
                    f"  unicode-range: {span};",
                    "}",
                ]
            )
        )
        faces[family].append((weight, style, subset))
    header = (
        "/* IBM Plex (SIL Open Font License 1.1, see frontend/fonts/OFL.txt).\n"
        " * Generated by scripts/gen_font_css.py from the WOFF2 files in frontend/fonts.\n"
        " * Do not edit by hand. */\n"
    )
    return header + "\n".join(rules) + "\n"


def main() -> int:
    if not FONT_DIR.is_dir():
        print(f"Missing {FONT_DIR}; run scripts/build_fonts.py first.", file=sys.stderr)
        return 1
    OUTPUT.write_text(build_css(), encoding="utf-8")
    count = len(list(FONT_DIR.glob("*.woff2")))
    print(f"Wrote {OUTPUT.relative_to(REPO_ROOT)} for {count} font files.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
